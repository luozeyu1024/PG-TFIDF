#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
v4_LLM_prediction_cluster_to_cell.py

Map cluster-level LLM predictions back to individual cells.

Features:
1. Read cluster-level predictions generated by v4.py (xlsx).
2. Read the reference label file (cell IDs and cluster assignments).
3. Assign each cell the predicted label of its cluster.
4. Write cell-level predictions (xlsx).

Input Format:
- cluster_prediction_xlsx: contains Cluster_UID, Predicted_Label, Confidence, etc.
- reference_label_xlsx: contains Cell_ID and clustering columns (e.g., Kmeans_Cluster, Louvain_Cluster).

Output Format:
- cell_id: cell ID
- {cluster_col}_prediction: predicted label for this clustering method
- {cluster_col}_confidence: prediction confidence
- {cluster_col}_qc_flags: QC flags (JSON string)
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import pandas as pd
from tqdm import tqdm


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Map cluster-level LLM predictions to cell-level labels."
    )
    
    parser.add_argument(
        "--cluster_prediction_xlsx",
        type=str,
        default=None,
        help="Path to cluster-level prediction xlsx from v4.py. "
             "If not provided, will try to auto-detect from output_path."
    )
    
    parser.add_argument(
        "--reference_label_xlsx",
        type=str,
        required=True,
        help="Path to reference label xlsx containing Cell_ID and cluster assignments."
    )
    
    parser.add_argument(
        "--save_path",
        type=str,
        required=True,
        help="Output path for cell-level predictions. "
             "Can be a directory (will auto-generate filename) or a specific .xlsx file."
    )
    
    parser.add_argument(
        "--cell_id_col",
        type=str,
        default="Cell_ID",
        help="Column name for cell ID in reference_label_xlsx. Default: Cell_ID"
    )
    
    parser.add_argument(
        "--cluster_cols",
        type=str,
        default=None,
        help="Comma-separated cluster column names to process. "
             "If not provided, auto-detect from reference_label_xlsx (columns containing 'cluster')."
    )
    
    return parser.parse_args()


def load_cluster_predictions(xlsx_path: Path) -> pd.DataFrame:
    """Load cluster-level predictions from v4.py output."""
    if not xlsx_path.exists():
        raise FileNotFoundError(f"Cluster prediction file not found: {xlsx_path}")
    
    xlsx = pd.ExcelFile(str(xlsx_path))
    
    # v4.py typically writes a 'predictions' sheet.
    sheet_name = 'predictions' if 'predictions' in xlsx.sheet_names else xlsx.sheet_names[0]
    df = pd.read_excel(xlsx, sheet_name=sheet_name)
    
    # Standardize column names, handling possible variants.
    col_mapping = {}
    for col in df.columns:
        col_lower = col.lower().replace(' ', '_')
        if 'cluster_uid' in col_lower or 'cluster_id' in col_lower:
            col_mapping[col] = 'Cluster_UID'
        elif 'cluster_col' in col_lower:
            col_mapping[col] = 'Cluster_Col'
        elif 'cluster_label' in col_lower:
            col_mapping[col] = 'Cluster_Label'
        elif 'predicted_label' in col_lower or 'prediction' in col_lower:
            col_mapping[col] = 'Predicted_Label'
        elif 'confidence' in col_lower:
            col_mapping[col] = 'Confidence'
        elif 'qc' in col_lower or 'flags' in col_lower:
            col_mapping[col] = 'QC_Flags_JSON'
    
    df = df.rename(columns=col_mapping)
    
    # Validate required columns.
    required = ['Cluster_UID', 'Predicted_Label']
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in prediction file: {missing}. "
                        f"Available columns: {df.columns.tolist()}")
    
    return df


def build_cluster_lookup(predictions_df: pd.DataFrame) -> Dict[str, Dict[str, any]]:
    """Build lookup dict: Cluster_UID -> {predicted_label, confidence, qc_flags}."""
    lookup = {}
    
    for _, row in predictions_df.iterrows():
        cluster_uid = str(row['Cluster_UID'])
        lookup[cluster_uid] = {
            'predicted_label': row.get('Predicted_Label', 'Unknown'),
            'confidence': row.get('Confidence', 0.0),
            'qc_flags': row.get('QC_Flags_JSON', '[]')
        }
    
    return lookup


def parse_cluster_uid(cluster_uid: str) -> Tuple[str, str]:
    """Parse Cluster_UID like 'Kmeans_Cluster::0' -> ('Kmeans_Cluster', '0')."""
    if '::' in cluster_uid:
        parts = cluster_uid.split('::')
        return parts[0], parts[1]
    # Fallback: try to guess
    return None, cluster_uid


def get_cluster_columns(ref_df: pd.DataFrame, specified_cols: Optional[str], cell_id_col: str) -> List[str]:
    """Determine which columns are cluster assignments."""
    if specified_cols:
        cols = [c.strip() for c in specified_cols.split(',') if c.strip()]
        # Validate
        invalid = [c for c in cols if c not in ref_df.columns]
        if invalid:
            raise ValueError(f"Specified cluster columns not found: {invalid}")
        return cols
    
    # Auto-detect: columns containing 'cluster' (case-insensitive) except cell_id_col
    cols = []
    for col in ref_df.columns:
        if col == cell_id_col:
            continue
        if 'cluster' in col.lower():
            cols.append(col)
    
    if not cols:
        raise ValueError(f"No cluster columns detected. Available columns: {ref_df.columns.tolist()}")
    
    return cols


def map_clusters_to_cells(
    ref_df: pd.DataFrame,
    cluster_lookup: Dict[str, Dict],
    cluster_cols: List[str],
    cell_id_col: str
) -> pd.DataFrame:
    """Map cluster predictions to each cell."""
    
    result = pd.DataFrame()
    result[cell_id_col] = ref_df[cell_id_col]
    
    # Create a prediction mapping for each cluster column.
    for cluster_col in cluster_cols:
        predictions = []
        confidences = []
        qc_flags_list = []
        
        for _, row in tqdm(ref_df.iterrows(), total=len(ref_df), desc=f"Mapping {cluster_col}"):
            cluster_label = row[cluster_col]
            
            # Construct Cluster_UID.
            if pd.isna(cluster_label):
                # Handle missing values.
                predictions.append('Unknown')
                confidences.append(0.0)
                qc_flags_list.append('[]')
                continue
            
            cluster_uid = f"{cluster_col}::{int(cluster_label) if isinstance(cluster_label, (int, float)) else cluster_label}"
            
            # Look up the prediction.
            pred_info = cluster_lookup.get(cluster_uid)
            if pred_info:
                predictions.append(pred_info['predicted_label'])
                confidences.append(pred_info['confidence'])
                qc_flags_list.append(pred_info['qc_flags'])
            else:
                # No prediction found (the cluster may be absent from the prediction file).
                predictions.append('Unknown')
                confidences.append(0.0)
                qc_flags_list.append('[]')
        
        # Add columns.
        result[f"{cluster_col}_prediction"] = predictions
        result[f"{cluster_col}_confidence"] = confidences
        result[f"{cluster_col}_qc_flags"] = qc_flags_list
    
    return result


def generate_output_filename(save_path: Path, task_name: str, model_name: str) -> Path:
    """Generate output filename based on task and model info."""
    if save_path.suffix == '.xlsx':
        return save_path
    
    # save_path is a directory
    save_path.mkdir(parents=True, exist_ok=True)
    
    # Clean task name for filename
    safe_task = re.sub(r'[^\w\s-]', '_', task_name).strip().replace(' ', '_')
    safe_model = re.sub(r'[^\w\s-]', '_', model_name).strip().replace(' ', '_')
    
    filename = f"{safe_model}__{safe_task}__cell_level_predictions.xlsx"
    return save_path / filename


def extract_task_info(predictions_df: pd.DataFrame, xlsx_path: Path) -> Tuple[str, str]:
    """Extract task name and model name from prediction data or filename."""
    # Try to extract from filename
    # Example: anthropic_claude_sonnet_4_6__CellTypeAnnotation__cluster_level_v4_batch.xlsx
    filename = xlsx_path.stem
    
    task_name = "UnknownTask"
    model_name = "UnknownModel"
    
    parts = filename.split('__')
    if len(parts) >= 2:
        model_name = parts[0]
        task_name = parts[1]
    
    return task_name, model_name


def auto_detect_prediction_file(output_path: Path) -> Optional[Path]:
    """Auto-detect cluster prediction file from output path."""
    # Look for common patterns
    patterns = [
        "*__cluster_level_v4_batch.xlsx",
        "*__predictions.xlsx",
        "*_cluster_predictions.xlsx"
    ]
    
    for pattern in patterns:
        matches = list(output_path.glob(pattern))
        if matches:
            return matches[0]
    
    # Look for any xlsx file
    xlsx_files = list(output_path.glob("*.xlsx"))
    if xlsx_files:
        return xlsx_files[0]
    
    return None


def main() -> int:
    args = parse_args()
    
    print("=" * 60)
    print("v4_LLM_prediction_cluster_to_cell")
    print("=" * 60)
    
    # Resolve cluster prediction path
    if args.cluster_prediction_xlsx:
        pred_path = Path(args.cluster_prediction_xlsx)
    else:
        # Try to auto-detect from save_path directory or use demo path
        save_path = Path(args.save_path)
        if save_path.is_dir():
            pred_path = auto_detect_prediction_file(save_path)
        else:
            pred_path = auto_detect_prediction_file(save_path.parent)
        
        if pred_path is None:
            raise ValueError("--cluster_prediction_xlsx not provided and auto-detection failed.")
    
    print(f"[INFO] Loading cluster predictions from: {pred_path}")
    predictions_df = load_cluster_predictions(pred_path)
    print(f"[INFO] Loaded {len(predictions_df)} cluster predictions")
    print(f"[INFO] Clusters: {predictions_df['Cluster_UID'].tolist()[:5]}...")
    
    # Load reference labels
    ref_path = Path(args.reference_label_xlsx)
    print(f"[INFO] Loading reference labels from: {ref_path}")
    ref_df = pd.read_excel(str(ref_path))
    print(f"[INFO] Loaded {len(ref_df)} cells")
    
    # Determine cluster columns
    cluster_cols = get_cluster_columns(ref_df, args.cluster_cols, args.cell_id_col)
    print(f"[INFO] Processing cluster columns: {cluster_cols}")
    
    # Build lookup
    cluster_lookup = build_cluster_lookup(predictions_df)
    print(f"[INFO] Built lookup for {len(cluster_lookup)} clusters")
    
    # Map to cells
    print(f"[INFO] Mapping cluster predictions to cells...")
    result_df = map_clusters_to_cells(ref_df, cluster_lookup, cluster_cols, args.cell_id_col)
    
    # Determine output path
    task_name, model_name = extract_task_info(predictions_df, pred_path)
    output_path = generate_output_filename(Path(args.save_path), task_name, model_name)
    
    # Save
    output_path.parent.mkdir(parents=True, exist_ok=True)
    result_df.to_excel(str(output_path), index=False)
    print(f"[INFO] Saved cell-level predictions to: {output_path}")
    
    # Summary
    print("\n" + "=" * 60)
    print("Summary")
    print("=" * 60)
    print(f"Total cells: {len(result_df)}")
    print(f"Cluster columns processed: {len(cluster_cols)}")
    for col in cluster_cols:
        pred_col = f"{col}_prediction"
        value_counts = result_df[pred_col].value_counts()
        print(f"\n{col} predictions:")
        for label, count in value_counts.items():
            print(f"  {label}: {count} cells ({count/len(result_df)*100:.1f}%)")
    
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
